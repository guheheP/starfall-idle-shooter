import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { Plugin } from 'vite';

/** Keep caching restricted to the shipped game, even on a shared github.io origin. */
export function createServiceWorker(files: readonly string[], revision: string, shellDigest: string): string {
  return `/* Generated by the STARFALL build. Do not edit dist/sw.js. */
const SCOPE = self.registration.scope;
const CACHE_PREFIX = 'starfall-pwa:' + new URL(SCOPE).pathname + ':';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(revision)};
const RESOURCES = ${JSON.stringify(files)}.map(path => new URL(path, SCOPE).href);
const ALLOWED = new Set(RESOURCES);
const SHELL = new URL('index.html', SCOPE).href;
const SHELL_DIGEST = ${JSON.stringify(shellDigest)};

async function isReleaseShell(response) {
  if (!response?.ok) return false;
  const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
  const hex = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
  return hex === SHELL_DIGEST;
}

async function fillMissing(cache, missing) {
  let shell;
  if (missing.includes(SHELL)) {
    shell = await fetch(new Request(SHELL, { cache: 'reload' }));
    if (!await isReleaseShell(shell)) throw new Error('The game shell belongs to a different release.');
  }
  await cache.addAll(missing.filter(url => url !== SHELL).map(url => new Request(url, { cache: 'reload' })));
  if (shell) await cache.put(SHELL, shell);
}

async function cachedResources(cache) {
  const present = await Promise.all(RESOURCES.map(url => cache.match(url)));
  const shellIndex = RESOURCES.indexOf(SHELL);
  if (shellIndex < 0 || !await isReleaseShell(present[shellIndex])) return { present, shellMatches: false };
  return { present, shellMatches: true };
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME);
      await fillMissing(cache, RESOURCES);
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
  // A new release waits until all old game windows have closed. Never interrupt a run.
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== new URL(SCOPE).origin) return;
  const isGameNavigation = request.mode === 'navigate'
    && (url.pathname === new URL(SCOPE).pathname || url.pathname === new URL(SHELL).pathname);
  const key = isGameNavigation ? SHELL : url.href;
  if (!ALLOWED.has(key)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(key);
    if (cached && (key !== SHELL || await isReleaseShell(cached))) return cached;
    // Cache eviction must not be reported as offline-ready. A successful online read repairs it.
    const response = await fetch(request);
    if (response.ok && (key !== SHELL || await isReleaseShell(response))) await cache.put(key, response.clone());
    return response;
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type !== 'STARFALL_OFFLINE_STATUS' || !event.ports[0]) return;
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME);
      const status = await cachedResources(cache);
      if (event.data.repair === true && (!status.present.every(Boolean) || !status.shellMatches)) {
        const missing = RESOURCES.filter((url, index) => !status.present[index] || (url === SHELL && !status.shellMatches));
        await fillMissing(cache, missing);
        const repaired = await cachedResources(cache);
        event.ports[0].postMessage({ ready: repaired.present.every(Boolean) && repaired.shellMatches });
      } else {
        event.ports[0].postMessage({ ready: status.present.every(Boolean) && status.shellMatches });
      }
    } catch {
      event.ports[0].postMessage({ ready: false });
    }
  })());
});
`;
}

async function shippedFiles(directory: string, prefix = ''): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}${entry.name}`;
    if (entry.isDirectory()) files.push(...await shippedFiles(join(directory, entry.name), `${relative}/`));
    else if (relative === 'index.html' || relative === 'manifest.webmanifest'
      || /^(assets|icons)\/.*\.(?:js|css|png|webp|jpe?g|svg|ico|woff2?)$/i.test(relative)) files.push(relative);
  }
  return files.sort();
}

export function gamePwa(): Plugin {
  let directory = '';
  return {
    name: 'starfall-offline-game',
    apply: 'build',
    configResolved(config) { directory = join(config.root, config.build.outDir); },
    async closeBundle() {
      const files = await shippedFiles(directory);
      if (!files.includes('index.html') || !files.includes('manifest.webmanifest')) {
        throw new Error('PWA build is missing its game shell or manifest.');
      }
      const hash = createHash('sha256');
      const shellDigest = createHash('sha256').update(await readFile(join(directory, 'index.html'))).digest('hex');
      hash.update(createServiceWorker(files, 'revision', shellDigest));
      for (const file of files) {
        hash.update(file);
        hash.update(await readFile(join(directory, file)));
      }
      await writeFile(join(directory, 'sw.js'), createServiceWorker(files, hash.digest('hex').slice(0, 20), shellDigest));
    },
  };
}
